// Cleanup applied to make the decompile compile:
//   - stripped ILSpy's ((AbstractGmdcExporter)this).X protected-access
//     upcasts (illegal in modern C#)
//   - stripped //IL_XXX: Unknown result type comment noise
//   - wrapped negative int -> ElementIdentity casts in unchecked((uint)-N)
//
// Autogenerated variable names (num, val, flag, array, text) are
// preserved intentionally to minimize divergence from working code.
// Round-trip export/import was validated end-to-end before commit;
// semantic renaming is deferred so future edits can rename
// incrementally as they touch each section.
//
// Magic-number decode for the more opaque ElementIdentity comparisons:
//   -1149040725 = 0xBB8307AB = UVCoordinate
//    1559416801 = 0x5CF2CFE1 = MorphVertexDelta
//    -881902998 = 0xCB6F3A6A = NormalMorphDelta
