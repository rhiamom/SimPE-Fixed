	private Vector3f Correct(Vector3f t, object cor)
	{
		if (cor == null)
		{
			return t;
		}
		if (cor is Quaternion)
		{
			return t;
		}
		if (!(cor is Vector3f))
		{
			return t;
		}
		return t + (Vector3f)cor;
	}

	private Quaternion Correct(Quaternion t, object cor)
	{
		if (cor == null)
		{
			return t;
		}
		if (!(cor is Quaternion))
		{
			return t;
		}
		return t * (Quaternion)cor;
	}

